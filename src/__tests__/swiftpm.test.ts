describe('readIosPermissions', () => {
  let configPath: string;

  const readConfig = (permissions: unknown): ReturnType<typeof readIosPermissions> => {
    fs.writeFileSync(configPath, JSON.stringify(permissions));
    return readIosPermissions(configPath);
  };

  beforeEach(() => {
    configPath = path.join(
      fs.mkdtempSync(path.join(os.tmpdir(), 'rnp-config-')),
      'react-native-permissions.json',
    );
  });

  afterEach(() => fs.rmSync(path.dirname(configPath), {recursive: true, force: true}));

  test('uses the list in react-native-permissions.json', () => {
    assert.deepEqual(readConfig(['Camera', 'Contacts', 'Camera']), ['Camera', 'Contacts']);
  });

  test('returns an empty list and warns when the file is missing', () => {
    const warned = warnings();

    assert.deepEqual(readIosPermissions(configPath), []);
    assert.equal(warned().length, 1);
    assert.match(warned()[0] ?? '', /no permission handlers will be compiled/i);
    assert.match(warned()[0] ?? '', /ios\/react-native-permissions\.json/);
  });

  test('throws, naming the file, when the list is not an array of strings', () => {
    const namesFile = (error: Error): boolean => error.message.includes(configPath);

    assert.throws(() => readConfig('Camera'), namesFile);
    assert.throws(() => readConfig(['Camera', 42]), namesFile);
  });

  test('throws, naming the file, when the JSON is malformed', () => {
    fs.writeFileSync(configPath, '["Camera",');

    assert.throws(
      () => readIosPermissions(configPath),
      (error: Error): boolean =>
        error.message.startsWith(`[Permissions] Could not read ${configPath}:`),
    );
  });

  test('warns about and drops unknown names', () => {
    const warned = warnings();

    assert.deepEqual(readConfig(['Camera', 'Foo', 'Contacts', 'Bar']), ['Camera', 'Contacts']);
    assert.deepEqual(warned(), ['[Permissions] Unknown permissions: Foo, Bar']);
  });
});

describe('permissions config', () => {
  test('lists every handler folder in ios/', () => {
    const folders = fs
      .readdirSync(path.join(libraryRoot, 'ios'), {withFileTypes: true})
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name);

    assert.deepEqual([...iosPermissions].sort(), folders.sort());
  });

  test('matches the frameworks map in scripts/setup.rb', () => {
    const setup = fs.readFileSync(path.join(libraryRoot, 'scripts', 'setup.rb'), 'utf8');
    const setupFrameworks: Record<string, string[]> = {};

    for (const line of setup.split('\n')) {
      const entry = /^\s*'(\w+)' => \[(.*)\],?$/.exec(line);

      if (entry?.[1] != null && entry[2] != null) {
        setupFrameworks[entry[1]] = entry[2].split(', ').map((name) => name.replace(/'/g, ''));
      }
    }

    assert.deepEqual(setupFrameworks, iosPermissionFrameworks);
  });
});

